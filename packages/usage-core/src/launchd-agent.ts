// The LaunchAgent a headless product's `service install` writes on macOS
// (ADR-0143 §4, §10): its plist text, a pure function of the product's
// descriptor, the command that starts it, the installing shell's environment
// and working directory, and the log file. The product passes its label and
// `serve` arguments and the variables to bake, as it passes its systemd unit
// to ./systemd-unit (ADR-0127 §11).
//
// Reachable only via the "./launchd-agent" subpath, never index.ts.

import { join } from "node:path";

import { type Env, home } from "./home-path";
import { type BakedVariable, bakedEnvironment } from "./systemd-unit";

/** One headless product's LaunchAgent. */
export interface LaunchAgent {
  /** The binary, and every command a hint names: "maxprice". */
  name: string;
  /** The job's Label, and the plist's file name: "com.maxprice.headless-client". */
  label: string;
  /** ProgramArguments after the command: ["serve"]. */
  execArgs: readonly string[];
  /** The variables baked into EnvironmentVariables when the installing shell sets them. */
  baked: readonly BakedVariable[];
}

/**
 * The variable that tells `serve` launchd supervises it, so it keeps its own
 * relaunch ledger and rotates its log (ADR-0143 §5–§6). Every agent's plist
 * sets it; the README's LaunchDaemon sets it by hand (§9).
 */
export const SUPERVISOR = { name: "MAXPRICE_SUPERVISOR", value: "launchd" } as const;

/** ADR-0120's RestartSec=10s, as launchd spaces relaunches. */
export const THROTTLE_SECONDS = 10;

// `~/Library/LaunchAgents/<label>.plist`: the per-user agents directory,
// which launchd loads at each login.
export function agentPlistPath(agent: Pick<LaunchAgent, "label">, env: Env): string {
  return join(home(env), "Library", "LaunchAgents", `${agent.label}.plist`);
}

// `gui/<uid>`: the user's login session's domain, where the agent runs.
export function guiDomain(uid: number): string {
  return `gui/${uid}`;
}

// `gui/<uid>/<label>`: the agent within it, as launchctl's verbs name it.
export function agentTarget(agent: Pick<LaunchAgent, "label">, uid: number): string {
  return `${guiDomain(uid)}/${agent.label}`;
}

// The same target as a line the user pastes: `$(id -u)` stands in for the
// uid, so one line serves every user, root's advice included (ADR-0143 §8).
export function shellTarget(agent: Pick<LaunchAgent, "label">): string {
  return `gui/$(id -u)/${agent.label}`;
}

// The command the agent runs, as messages name it: "maxprice serve".
export function agentServeCommand(agent: LaunchAgent): string {
  return [agent.name, ...agent.execArgs].join(" ");
}

// The variables the plist sets: the marker, then each baked variable the
// installing shell sets, by ./systemd-unit's rule (ADR-0143 §4: "made
// absolute as ADR-0120 §4 makes them").
export function agentEnvironment(
  agent: LaunchAgent,
  env: Env,
  cwd: string,
): [name: string, value: string][] {
  return [[SUPERVISOR.name, SUPERVISOR.value], ...bakedEnvironment(agent, env, cwd)];
}

// XML's five predefined entities; a plist string holds any other character
// as it is. A control character other than tab and newline is not allowed
// in XML 1.0 at all, so it cannot reach a plist: none of the agent's values
// (a path, a label) carries one that launchd could use.
function xml(text: string): string {
  return text
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;");
}

function stringEntry(key: string, value: string, indent: string): string[] {
  return [`${indent}<key>${xml(key)}</key>`, `${indent}<string>${xml(value)}</string>`];
}

// `command` starts this product: the compiled binary's absolute path, or bun
// and its entry when run from source. `logPath` is `<data dir>/serve.log` of
// the data dir the agent will serve, for its stdout and stderr both (§6).
export function plistText(
  agent: LaunchAgent,
  command: readonly string[],
  env: Env,
  cwd: string,
  logPath: string,
): string {
  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
    `<!-- Generated by \`${agent.name} service install\`, which rewrites this file. -->`,
    '<plist version="1.0">',
    "<dict>",
    ...stringEntry("Label", agent.label, "  "),
    "  <key>ProgramArguments</key>",
    "  <array>",
    ...[...command, ...agent.execArgs].map((word) => `    <string>${xml(word)}</string>`),
    "  </array>",
    "  <key>EnvironmentVariables</key>",
    "  <dict>",
    ...agentEnvironment(agent, env, cwd).flatMap(([name, value]) =>
      stringEntry(name, value, "    "),
    ),
    "  </dict>",
    "  <key>RunAtLoad</key>",
    "  <true/>",
    "  <key>KeepAlive</key>",
    "  <dict>",
    "    <key>SuccessfulExit</key>",
    "    <false/>",
    "  </dict>",
    "  <key>ThrottleInterval</key>",
    `  <integer>${THROTTLE_SECONDS}</integer>`,
    ...stringEntry("StandardOutPath", logPath, "  "),
    ...stringEntry("StandardErrorPath", logPath, "  "),
    "</dict>",
    "</plist>",
    "",
  ].join("\n");
}

// The plist's EnvironmentVariables, read back from a file this module wrote,
// for a verb that finds the plist on disk but the job not loaded. Only the
// `<key>`/`<string>` pairs inside that dict are read, which is every form
// plistText writes; a file someone reshaped by hand reads as setting none.
export function plistEnvironment(text: string): Record<string, string> {
  const dict = /<key>EnvironmentVariables<\/key>\s*<dict>([\s\S]*?)<\/dict>/.exec(text);
  if (dict === null) return {};
  const vars: Record<string, string> = {};
  for (const [, key, value] of dict[1]!.matchAll(
    /<key>([^<]*)<\/key>\s*<string>([^<]*)<\/string>/g,
  )) {
    vars[unxml(key!)] = unxml(value!);
  }
  return vars;
}

function unxml(text: string): string {
  return text
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">")
    .replaceAll("&quot;", '"')
    .replaceAll("&apos;", "'")
    .replaceAll("&amp;", "&");
}
