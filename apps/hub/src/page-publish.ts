// `maxprice-hub page`, `page set`, `page clear` and `page snippet` (ADR-0125
// §3): the Hub page URL's report and probe, its setting, and the Apache
// snippet that publishes the page there. The Hub never writes web-server
// config: it prints the snippet, and a human installs it with sudo. None of
// the four takes serve.lock or needs the Hub stopped, since the daemon reads
// the URL only for its boot log (§5). All config writers hold a short,
// separate lock over their entire read-modify-write.
//
// Setup (ADR-0128) takes three pieces from here. Its step 3 is `page set`'s
// effect without the snippet, setHubPageUrl (§3); its ending prints
// probePage's reading (§5) and the Apache lines, PAGE_APACHE_LINES, but not
// the `maxprice-hub page` check, PAGE_CHECK_LINE, which its Enter replaces.

// The snippet (ADR-0125 §6) for a URL checkHubPageUrl accepted. Its path
// holds only [A-Za-z0-9._~-], so `.` is the one character the anchored
// RedirectMatch regex escapes; Apache's mod_dir would 404 the bare path. A
// root path has no bare path to redirect. No <IfModule> guard, so with no
// proxy module loaded configtest fails on ProxyPass (with mod_proxy alone it
// passes and the path answers 500, measured); no Require, Header,
// ProxyPreserveHost or timeout: the server's access policy decides who sees
// the page, the Hub sends ADR-0124 §8's headers, and the default
// ProxyPreserveHost Off hands the Hub a loopback Host (ADR-0124 §2).
export function pageSnippet({
  url,
  port,
  version,
}: {
  url: string;
  port: number;
  version: string;
}): string {
  const path = new URL(url).pathname;
  const target = `http://127.0.0.1:${port}/page/`;
  return lines([
    `# MaxPrice Hub page — generated by maxprice-hub ${version} for ${url}`,
    `# Proxies to the Hub on 127.0.0.1:${port}. Regenerate (maxprice-hub page snippet) after changing`,
    "# the Hub's port or page URL. Sets no headers: the Hub sends its own CSP and caching (ADR-0124).",
    "# Needs mod_proxy_http.",
    ...(path === "/"
      ? []
      : [`RedirectMatch 301 ^${path.slice(0, -1).replaceAll(".", "\\.")}$ ${path}`]),
    `<Location ${path}>`,
    `    ProxyPass        ${target}`,
    `    ProxyPassReverse ${target}`,
    "</Location>",
  ]);
}

// What any other web server must do (ADR-0125 §6, with ADR-0124 §2's Host
// rule from #493), as one line.
export function pageContract(url: string, port: number): string {
  const path = new URL(url).pathname;
  const redirect = path === "/" ? "" : `, and redirect ${path.slice(0, -1)} to ${path}`;
  return `Other web servers: proxy ${path} to http://127.0.0.1:${port}/page/ and nothing else, send it a loopback Host such as 127.0.0.1:${port} rather than the visitor's, add no headers${redirect}.`;
}

// ADR-0125 §7: the distribution's idiom, conf-available with a2enconf, which
// applies to every vhost; the binary assumes no host-specific layout. One
// line each, unindented, comments aligned: the Apache lines, then the check
// that the page is published. `page` prints them all, indented two spaces
// (PAGE_INSTALL_STEPS). Setup's ending lists the Apache lines alone among
// its sudo steps, since its Enter makes the check (ADR-0128 §5).
export const PAGE_APACHE_LINES: readonly string[] = [
  "sudo a2enmod proxy_http                      # pulls in proxy; first time only",
  "maxprice-hub page snippet | sudo tee /etc/apache2/conf-available/maxprice-hub.conf",
  "sudo a2enconf maxprice-hub",
  "sudo apache2ctl configtest",
  "sudo systemctl restart apache2               # after a2enmod; a reload for later snippet changes",
];

export const PAGE_CHECK_LINE =
  'maxprice-hub page                            # should read "published"';

export const PAGE_INSTALL_STEPS = lines(
  [...PAGE_APACHE_LINES, PAGE_CHECK_LINE].map((line) => `  ${line}`),
);

// What `page`'s probe found (ADR-0125 §4).
export type PageReading =
  | { kind: "published" }
  | { kind: "hub-not-running"; detail: string }
  | { kind: "another-hub"; version: string }
  | { kind: "not-a-view" }
  // 403
  | { kind: "refused" }
  // 404
  | { kind: "not-installed" }
  // 502, 503
  | { kind: "unreachable"; status: number }
  | { kind: "status"; status: number }
  | { kind: "no-answer"; error: string };

// `<pageUrl>view`'s answer, by §4's table. A 200 is the page only when its
// body is a view, which names the service, and of this Hub's version.
export function readViewAnswer(
  answer: { status: number; body: string },
  version: string,
): PageReading {
  const { status, body } = answer;
  if (status === 200) {
    let parsed: unknown;
    try {
      parsed = JSON.parse(body);
    } catch {
      return { kind: "not-a-view" };
    }
    const view = hubPageViewSchema.safeParse(parsed);
    if (!view.success) return { kind: "not-a-view" };
    return view.data.version === version
      ? { kind: "published" }
      : { kind: "another-hub", version: view.data.version };
  }
  if (status === 403) return { kind: "refused" };
  if (status === 404) return { kind: "not-installed" };
  if (status === 502 || status === 503) return { kind: "unreachable", status };
  return { kind: "status", status };
}

// The words after `Reading: `.
export function readingLine(reading: PageReading, viewUrl: string, version: string): string {
  switch (reading.kind) {
    case "published":
      return "published";
    case "hub-not-running":
      return `Hub not running: ${reading.detail}`;
    case "another-hub":
      return `another Hub's page: ${viewUrl} answers maxprice-hub ${reading.version}, and this Hub is ${version}`;
    case "not-a-view":
      return `something other than the Hub page answers at ${viewUrl}`;
    case "refused":
      return `the web server refused this machine (403 from ${viewUrl})`;
    case "not-installed":
      return `the snippet is not installed (404 from ${viewUrl})`;
    case "unreachable":
      return `the web server cannot reach the Hub (${reading.status} from ${viewUrl}); if the Hub's port changed, regenerate and reinstall the snippet`;
    case "status":
      return `${viewUrl} answered ${reading.status}`;
    case "no-answer":
      return `no answer from ${viewUrl}: ${reading.error}`;
  }
}

export type PageDeps = {
  io: Io;
  env?: Record<string, string | undefined>;
  platform?: NodeJS.Platform;
  version?: string;
  // The request for `<url>view`; direct-http.ts's, which no proxy reaches,
  // by default.
  get?: DirectGet;
  // Whether a Hub answers /healthz on 127.0.0.1:<port>; asked over
  // loopback-http.ts's socket by default.
  hubAnswers?: (port: number) => Promise<boolean>;
  // serve.lock's record; readServeLockHolder by default.
  readLockHolder?: (dataDir: string) => ServeLockHolder;
  viewTimeoutMs?: number;
};

function lines(text: readonly string[]): string {
  return `${text.join("\n")}\n`;
}

// hub.json as `page` and `page snippet` read it, refused when boot would
// degrade it to the defaults (`page set|clear` refuse it the same way, in
// saveHubPageUrl): its config, and its own pageUrl, read before the schema
// turns a rejected one into null, so the report can name it.
type StoredPageUrl =
  | { kind: "unset" }
  | { kind: "rejected"; value: unknown; reason: string }
  | { kind: "set"; url: string };

function readPageConfig(dataDir: string): { config: HubFileConfig; stored: StoredPageUrl } {
  const { raw, config, problem } = readHubConfig(dataDir);
  if (problem !== null) {
    throw new CliError(EXIT.FAILURE, `hub.json cannot be used: ${problem.reason}`);
  }
  const value = (raw as Record<string, unknown>).pageUrl;
  if (value === undefined || value === null) return { config, stored: { kind: "unset" } };
  const check = checkHubPageUrl(value);
  return {
    config,
    stored: check.ok
      ? { kind: "set", url: check.url }
      : { kind: "rejected", value, reason: check.reason },
  };
}

function tunnel(port: number): string[] {
  return [
    "Through an SSH tunnel, from your own machine:",
    `  ssh -L ${port}:127.0.0.1:${port} <host>`,
    `  then open http://127.0.0.1:${port}/page/`,
  ];
}

// What probePage reads beside its URL and port: PageDeps but the writer it
// never prints to, so setup's ending can ask it with none (ADR-0128 §5).
export type ProbeDeps = Omit<PageDeps, "io">;

// `page`'s probe (ADR-0125 §4), whose reading setup's ending prints too
// (ADR-0128 §5). First, whether the Hub runs, so a stopped one is not read
// as a web-server fault: on Linux, serve.lock's record names the pid and its
// port. It is read, never taken, as `service status` and the Headless
// client's `update` read theirs, so this check can never make a starting
// serve lose the lock and exit 5. A pid the kernel reused reads as running;
// /healthz then decides. Off Linux there is no lock, and hub.json's port is
// asked. Then `<url>view`, under one manual timer (not AbortSignal.timeout:
// the bun/win32 parked-loop bug, index.ts's getHealthz) that covers the
// body as well as the headers. Neither request goes through a proxy that
// HTTP_PROXY names: the Hub is asked on its own loopback over
// loopback-http.ts (answersHealthz), and the web server through `get`,
// direct-http.ts by default, as this machine reaches it, its name resolved
// here (ADR-0125, Consequences).
export async function probePage(
  dataDir: string,
  url: string,
  port: number,
  deps: ProbeDeps,
): Promise<PageReading> {
  const env = deps.env ?? process.env;
  const version = deps.version ?? VERSION;
  const get = deps.get ?? directGet;
  const hubAnswers = deps.hubAnswers ?? answersHealthz;
  const ms = deps.viewTimeoutMs ?? 5_000;
  let hubPort = port;
  if ((deps.platform ?? process.platform) === "linux") {
    const readLockHolder =
      deps.readLockHolder ?? ((dir: string) => readServeLockHolder(serveLockPath(dir), UNIT));
    const holder = readLockHolder(dataDir);
    if (holder.pid === null || !holder.running) {
      return {
        kind: "hub-not-running",
        detail: `serve.lock in ${displayPath(dataDir, env)} names no running maxprice-hub`,
      };
    }
    if (holder.port === null) {
      return {
        kind: "hub-not-running",
        detail: `serve.lock names pid ${holder.pid} but no port yet`,
      };
    }
    hubPort = holder.port;
  }
  if (!(await hubAnswers(hubPort))) {
    return { kind: "hub-not-running", detail: `no Hub answers /healthz on 127.0.0.1:${hubPort}` };
  }

  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), ms);
  try {
    return readViewAnswer(await get(`${url}view`, { signal: ctrl.signal }), version);
  } catch (error) {
    if (ctrl.signal.aborted) return { kind: "no-answer", error: `timed out after ${ms / 1000} s` };
    return { kind: "no-answer", error: errorText(error) };
  } finally {
    clearTimeout(timer);
  }
}

// An error as `message (code)`: node:net's carry a code, e.g. ECONNREFUSED,
// and getaddrinfo's e.g. ENOTFOUND.
function errorText(error: unknown): string {
  const message = error instanceof Error ? error.message : String(error);
  const code = (error as { code?: unknown } | null)?.code;
  return typeof code === "string" ? `${message} (${code})` : message;
}

// Whether a Hub answers /healthz on 127.0.0.1:<port>: a 2xx whose body names
// the service `maxprice-hub`, within 1.5 s. Over loopback-http.ts's socket,
// as the operator commands reach a running Hub (#497), so no proxy that
// HTTP_PROXY names is asked in its place; index.ts's hubAnswersAt asks the
// same over fetch.
async function answersHealthz(port: number): Promise<boolean> {
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), 1_500);
  try {
    const { status, body } = await loopbackRequest({
      port,
      method: "GET",
      path: "/healthz",
      signal: ctrl.signal,
    });
    return status >= 200 && status < 300 && JSON.parse(body)?.service === "maxprice-hub";
  } catch {
    return false;
  } finally {
    clearTimeout(timer);
  }
}

// `maxprice-hub page`: the report. Exit 0 when the page is published or no
// URL is set, a stored one the validator rejects included (the Hub treats it
// as unset, §2); 1 when one is set and the page is not published there, or
// hub.json cannot hold a config at all; 2 with no Hub at the data dir
// (requireHub). The loopback target, the tunnel
// and the snippet name hub.json's port; the probe asks the running Hub's.
export async function cliPage(deps: PageDeps): Promise<number> {
  const env = deps.env ?? process.env;
  const version = deps.version ?? VERSION;
  const dataDir = requireHub(env, deps.platform ?? process.platform);
  const { config, stored } = readPageConfig(dataDir);
  const { port } = config;
  const loopback = `Loopback: http://127.0.0.1:${port}/page/ (loopback peers only)`;

  // A stored value the validator rejects is unset (§2: the schema
  // `.catch(null)`s it), so it reads and exits as unset; the report names it.
  if (stored.kind !== "set") {
    deps.io.stdout.write(
      lines([
        "Hub page URL: not set",
        ...(stored.kind === "rejected"
          ? [
              `  hub.json holds ${terminalText(JSON.stringify(stored.value))}, which is not a Hub page URL: ${stored.reason}`,
            ]
          : []),
        loopback,
        ...tunnel(port),
        "To publish it through a web server: maxprice-hub page set <url>",
      ]),
    );
    return EXIT.OK;
  }

  const { url } = stored;
  const reading = await probePage(dataDir, url, port, deps);
  const report = [
    `Hub page URL: ${url}`,
    loopback,
    // A reading quotes what answered (another Hub's version, an error), so
    // nothing in it reaches the terminal as a control character.
    `Reading: ${terminalText(readingLine(reading, `${url}view`, version))}`,
    pageContract(url, port),
  ];
  if (reading.kind === "published") {
    deps.io.stdout.write(lines(report));
    return EXIT.OK;
  }
  deps.io.stdout.write(
    reading.kind === "hub-not-running"
      ? lines([...report, "", "Start the Hub, then run maxprice-hub page again."])
      : lines([...report, "", "Install the snippet on Debian or Ubuntu's Apache:"]) +
          PAGE_INSTALL_STEPS,
  );
  return EXIT.FAILURE;
}

// `page set`'s effect, in a data dir that holds a Hub: the URL checked, an
// invalid one exit 2 with hub.json untouched, then stored in its normalized
// form, which it returns. It prints nothing: `page set` prints the snippet
// after it, and setup's step 3 is this alone, the snippet left to its
// ending's install lines (ADR-0128 §3, §5).
export function setHubPageUrl(dataDir: string, input: string): string {
  const check = checkHubPageUrl(input);
  if (!check.ok) {
    throw new CliError(
      EXIT.USAGE,
      `${JSON.stringify(input)} is not a Hub page URL: ${check.reason}`,
    );
  }
  saveHubPageUrl(dataDir, check.url);
  return check.url;
}

// `maxprice-hub page set <url>`: an invalid URL is exit 2 with hub.json
// untouched. It reprints the snippet and calls any installed copy stale every
// time, an unchanged URL included, since nothing tracks one (§8).
export async function cliPageSet(input: string, deps: PageDeps): Promise<number> {
  const env = deps.env ?? process.env;
  const dataDir = requireHub(env, deps.platform ?? process.platform);
  const url = setHubPageUrl(dataDir, input);
  const { port } = readHubConfig(dataDir).config;
  deps.io.stdout.write(
    `Hub page URL set to ${url}; the Hub need not restart.\n\n` +
      pageSnippet({ url, port, version: deps.version ?? VERSION }) +
      lines([
        "",
        "Any installed copy of this snippet is now stale. Install this one, then check it with maxprice-hub page, which lists the install steps until the page is published.",
      ]),
  );
  return EXIT.OK;
}

// `maxprice-hub page clear`. The web server keeps its snippet, so it keeps
// publishing until a human removes it.
export async function cliPageClear(deps: PageDeps): Promise<number> {
  const env = deps.env ?? process.env;
  const dataDir = requireHub(env, deps.platform ?? process.platform);
  const { stored } = readPageConfig(dataDir);
  saveHubPageUrl(dataDir, null);
  deps.io.stdout.write(
    stored.kind === "unset"
      ? "No Hub page URL was set.\n"
      : "Hub page URL cleared; the Hub need not restart. A web server keeps publishing the page until its snippet is removed: on Debian or Ubuntu, sudo a2disconf maxprice-hub && sudo systemctl reload apache2.\n",
  );
  return EXIT.OK;
}

// `maxprice-hub page snippet`: the snippet alone on stdout, so `… | sudo tee
// <file>` installs it; with no valid URL set, exit 2 and nothing on stdout.
export async function cliPageSnippet(deps: PageDeps): Promise<number> {
  const env = deps.env ?? process.env;
  const dataDir = requireHub(env, deps.platform ?? process.platform);
  const { config, stored } = readPageConfig(dataDir);
  if (stored.kind === "unset") {
    throw new CliError(
      EXIT.USAGE,
      "no Hub page URL is set; set one with maxprice-hub page set <url>",
    );
  }
  if (stored.kind === "rejected") {
    throw new CliError(
      EXIT.USAGE,
      `hub.json holds ${JSON.stringify(stored.value)}, which is not a Hub page URL: ${stored.reason}; set one with maxprice-hub page set <url>`,
    );
  }
  deps.io.stdout.write(
    pageSnippet({ url: stored.url, port: config.port, version: deps.version ?? VERSION }),
  );
  return EXIT.OK;
}
