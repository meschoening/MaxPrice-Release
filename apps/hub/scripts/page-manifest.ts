// Writes the Hub page's manifest for the Headless Hub's linux-x64 compile
// (ADR-0124 §1, §7): apps/hub/generated/page-manifest.ts, one
// `with { type: "file" }` import per file of apps/hub-desktop/dist-page, so
// `bun build --compile` embeds each file's bytes, and a map from the file's
// path relative to `/page/` to the path `Bun.file()` reads it from. The
// compile run under `--conditions=maxprice-hub-page` resolves `#page-manifest`
// to this module (apps/hub/package.json's `imports`); every other build
// resolves the committed empty one, src/page-manifest.ts.
//
// build-binaries.ts runs this between the page build and the compile.
// `bun apps/hub/scripts/page-manifest.ts` runs it alone, for a source run under
// `bun --conditions=maxprice-hub-page`.
import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";

const HUB_DIR = resolve(import.meta.dir, "..");
export const PAGE_DIST_DIR = resolve(HUB_DIR, "..", "hub-desktop", "dist-page");
export const PAGE_MANIFEST_FILE = resolve(HUB_DIR, "generated", "page-manifest.ts");

const PAGE_BUILD = "bun --filter @maxprice/hub-desktop build:page";

/**
 * Every regular file under `distDir`, as its path relative to `distDir` with
 * `/` separators on every platform (the URL path below `/page/`), sorted.
 * Throws when `distDir` is missing or holds no `index.html` at its root: the
 * Hub would serve no page at `/page/`.
 */
export function listPageFiles(distDir: string): string[] {
  if (!existsSync(distDir)) {
    throw new Error(`No Hub page build at ${distDir}: run \`${PAGE_BUILD}\` first`);
  }
  const keys: string[] = [];
  const walk = (dir: string, prefix: readonly string[]) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      if (entry.isDirectory()) walk(join(dir, entry.name), [...prefix, entry.name]);
      else if (entry.isFile()) keys.push([...prefix, entry.name].join("/"));
    }
  };
  walk(distDir, []);
  if (!keys.includes("index.html")) {
    throw new Error(`The Hub page build at ${distDir} has no index.html: run \`${PAGE_BUILD}\``);
  }
  return keys.sort();
}

export type PageManifestEntry = {
  /** The file's path relative to `/page/`. */
  key: string;
  /** The import specifier, relative to the manifest module's directory. */
  specifier: string;
};

/** The manifest module's text. */
export function pageManifestSource(entries: readonly PageManifestEntry[]): string {
  const imports = entries.map(
    ({ specifier }, i) => `import p${i} from ${JSON.stringify(specifier)} with { type: "file" };`,
  );
  const fields = entries.map(({ key }, i) => `  ${JSON.stringify(key)}: p${i},`);
  return [
    "// Generated by apps/hub/scripts/page-manifest.ts from apps/hub-desktop/dist-page",
    "// for the Headless Hub's linux-x64 compile (ADR-0124 §1, §7). Do not edit it:",
    "// apps/hub/scripts/build-binaries.ts rewrites it before that compile, and git",
    "// ignores it.",
    ...imports,
    "",
    "export const PAGE_MANIFEST: Readonly<Record<string, string>> = {",
    ...fields,
    "};",
    "",
  ].join("\n");
}

/**
 * Writes the manifest of `distDir` to `outFile`, creating its directory, and
 * returns the keys it wrote. Each import is relative to `outFile`'s directory,
 * which is what Bun resolves it against.
 */
export function writePageManifest(distDir: string, outFile: string): string[] {
  const keys = listPageFiles(distDir);
  const rel = relative(dirname(outFile), distDir);
  // On Windows, a dist on another drive has no relative path: `relative`
  // answers an absolute one, which would become a `./D:/…` specifier.
  if (isAbsolute(rel)) throw new Error(`${distDir} has no path relative to ${outFile}`);
  const base = rel.split(sep).join("/");
  const prefix = base === "" ? "." : base.startsWith("../") || base === ".." ? base : `./${base}`;
  const source = pageManifestSource(keys.map((key) => ({ key, specifier: `${prefix}/${key}` })));
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, source);
  return keys;
}

if (import.meta.main) {
  const keys = writePageManifest(PAGE_DIST_DIR, PAGE_MANIFEST_FILE);
  console.log(`[page-manifest] ${keys.length} files → ${PAGE_MANIFEST_FILE}`);
}
